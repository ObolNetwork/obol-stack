#!/usr/bin/env bash
# Vendor the Gateway API standard-channel CRDs into the embedded
# gateway-api-crds chart (internal/embed/infrastructure/gateway-api-crds).
#
# Usage: scripts/update-gateway-api-crds.sh [vX.Y.Z]
#   Without an argument, re-vendors the version in the chart's appVersion
#   (what Renovate bumps). With one, also rewrites appVersion.
#
# Only the CustomResourceDefinitions are kept: Helm's crds/ directory is for
# CRDs, and the upstream safe-upgrades ValidatingAdmissionPolicy would also
# block a later switch to the experimental channel.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
chart="$repo_root/internal/embed/infrastructure/gateway-api-crds"
chart_yaml="$chart/Chart.yaml"
out="$chart/crds/standard-install.yaml"

version="${1:-}"
if [ -z "$version" ]; then
    version="$(sed -n 's/^appVersion: "\(v[0-9.]*\)"$/\1/p' "$chart_yaml")"
fi
if ! [[ "$version" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "error: bad Gateway API version '$version'" >&2
    exit 1
fi

url="https://github.com/kubernetes-sigs/gateway-api/releases/download/${version}/standard-install.yaml"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
echo "Fetching $url ..."
curl -fsSL -o "$tmp" "$url"

# Keep the license header, then every document whose kind is a CRD.
awk -v ver="$version" '
BEGIN { RS = "\n---\n"; ORS = "" }
NR == 1 {
    print "# Gateway API " ver " standard channel, CustomResourceDefinitions only.\n"
    print "# Generated by scripts/update-gateway-api-crds.sh from the upstream\n"
    print "# standard-install.yaml. Do not edit by hand.\n"
}
/(^|\n)kind: CustomResourceDefinition\n/ { print "---\n" $0 "\n" }
' "$tmp" > "$out"

sed -i.bak "s/^appVersion: \".*\"$/appVersion: \"$version\"/" "$chart_yaml" && rm -f "$chart_yaml.bak"
echo "Wrote $out ($(grep -c '^kind: CustomResourceDefinition' "$out") CRDs) for $version"
