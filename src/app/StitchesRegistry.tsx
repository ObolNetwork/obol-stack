'use client';

import { useRef, type ReactNode } from 'react';
import { useServerInsertedHTML } from 'next/navigation';
import { getCssText } from '@obolnetwork/obol-ui';
import { globalStyles } from '@/lib/ui/theme';

/**
 * Server-side style registry for Stitches (obol-ui).
 *
 * Stitches collects rules into an in-memory sheet as components render; on
 * the server nothing flushes that sheet into the HTML, so server-rendered
 * markup would arrive unstyled until hydration. This flushes the sheet
 * (theme tokens, globals and component rules) into a <style> tag as the
 * stream is written.
 */
export function StitchesRegistry({ children }: { children: ReactNode }) {
  globalStyles();
  const lastFlushed = useRef('');

  useServerInsertedHTML(() => {
    const css = getCssText();
    if (css === lastFlushed.current) return null;
    lastFlushed.current = css;
    return (
      <style
        id="stitches"
        // Generated by Stitches from our own style objects — not user input.
        dangerouslySetInnerHTML={{ __html: css }}
      />
    );
  });

  return <>{children}</>;
}
